-- 2. Post status enum -----------------------------------------------------
do $$ begin
  create type post_status as enum (
    'draft',            -- author is still writing
    'pending_review',   -- ready for editor (also used by daily-research bot)
    'scheduled',        -- approved, waiting for publish_at
    'published',        -- live
    'archived'          -- pulled from public list, still reachable by slug
  );
exception when duplicate_object then null; end $$;

